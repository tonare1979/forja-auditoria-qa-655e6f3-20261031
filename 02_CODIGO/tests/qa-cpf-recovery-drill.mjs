import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {cpfSchemaPlan} from '../ops/cpf-schema-plan.mjs';
import {createHash} from 'node:crypto';
import {mkdtempSync,writeFileSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
const db=new DatabaseSync(':memory:');
db.exec("CREATE TABLE users(id TEXT PRIMARY KEY,username TEXT NOT NULL);INSERT INTO users VALUES('old','legacy')");
const before=db.serialize();
for(const sql of cpfSchemaPlan(db.prepare('PRAGMA table_info(users)').all()))db.exec(sql);
db.prepare('INSERT INTO users(id,username,cpf) VALUES(?,?,?)').run('new','qa','52998224725');
assert.equal(db.prepare('SELECT count(*) n FROM users').get().n,2);
const dir=mkdtempSync(join(tmpdir(),'forja-cpf-restore-'));
const file=join(dir,'backup.sqlite');
writeFileSync(file,before);
const restored=new DatabaseSync(file);
assert.equal(restored.prepare('SELECT count(*) n FROM users').get().n,1);
assert.equal(restored.prepare("SELECT username FROM users WHERE id='old'").get().username,'legacy');
assert.equal(restored.prepare("SELECT count(*) n FROM pragma_table_info('users') WHERE name='cpf'").get().n,0);
assert.equal(createHash('sha256').update(restored.serialize()).digest('hex'),createHash('sha256').update(before).digest('hex'));
console.log('CPF_LOCAL_BACKUP_RESTORE_INTEGRITY_PASS');
db.close();restored.close();rmSync(dir,{recursive:true,force:true});
