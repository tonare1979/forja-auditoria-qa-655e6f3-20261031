import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const ctx={window:{}};vm.runInNewContext(readFileSync(new URL('../public/scout-progress.js',import.meta.url),'utf8'),ctx);
const now=new Date('2026-10-30T12:00:00Z');
const session=(id,date,equipment,kg,reps,sets=2)=>({id,date,code:'A',status:'complete',exercises:[{name:'Remada',...(equipment?{equipment}:{}),sets:Array.from({length:sets},()=>({kg,reps}))}]});
const base=session('a','2026-10-01','máquina 1',20,10),same=session('b','2026-10-12','máquina 1',22,10),switched=session('c','2026-10-22','máquina 2',40,10),legacy=session('d','2026-10-29',null,50,10);
const data={sessions:[base,JSON.parse(JSON.stringify(base)),same,switched,legacy]};
const summary=ctx.window.forjaScoutLongitudinal(data,now,30);
const remada=summary.exercises.find(e=>e.name==='Remada');
assert.equal(summary.sessions,4,'identical IDs should count once');
assert.equal(remada.observations,4);
assert.equal(remada.comparablePairs,1,'only first two records are provably comparable');
assert.equal(remada.improvements,1);
assert.equal(remada.inconclusive,2);
assert.match(remada.evidence[0].comparison,/2026-10-01.*2026-10-12/);
assert.equal(ctx.window.forjaScoutLongitudinal({sessions:[base,session('a','2026-10-02','máquina 1',99,10),same]},now,30).sessions,1,'conflicting IDs quarantined');
assert.equal(ctx.window.forjaScoutLongitudinal({sessions:[base,session('e','2026-10-12','máquina 1',25,5)]},now,30).exercises[0].improvements,0,'more load fewer reps not automatic progress');
assert.equal(ctx.window.forjaScoutLongitudinal({sessions:[base,session('f','2026-10-12','máquina 1',25,10,1)]},now,30).exercises[0].inconclusive,1,'different set count');
assert.match(ctx.window.forjaScoutProgress(data,now),/Evolução dos exercícios: últimos 30 dias/);
assert.match(ctx.window.forjaScoutProgress(data,now),/Consultar evidências/);
console.log('SCOUT_LONGITUDINAL_EVIDENCE_PASS');
