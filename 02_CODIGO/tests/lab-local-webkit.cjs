const assert=require('node:assert/strict'),fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {webkit,devices}=require('playwright');
(async()=>{
  const {createLab,credentials}=await import('../ops/lab-local.mjs');
  const directory=fs.mkdtempSync(path.join(os.tmpdir(),'forja-lab-'));
  let lab,browser;
  try{
    lab=await createLab({port:0,directory});browser=await webkit.launch();
    const ctx=await browser.newContext({...devices['iPhone 13'],ignoreHTTPSErrors:true});
    const page=await ctx.newPage();
    await ctx.route('**/*',route=>new URL(route.request().url()).hostname==='localhost'?route.continue():route.abort());
    await page.goto(lab.origin);
    await page.locator('[data-action="welcomeLogin"]').click();
    await page.locator('#welcomeCover').waitFor({state:'hidden'});
    await page.locator('#cloudUser').fill(credentials.username);
    await page.locator('#cloudPassword').fill(credentials.password);
    await page.locator('[data-action="cloudLogin"]').click();
    await page.waitForFunction(u=>cloud.user?.username===u,credentials.username);
    await page.locator('#nav [data-tab="treino"]').click();
    await page.waitForFunction(()=>tab==='treino');
    assert.ok(await page.locator('input[data-field="kg"]').count(),'actual workout inputs visible');
    assert.equal((await ctx.request.get(lab.origin+'/api/auth/me')).status(),200,'real cookie accepted by backend');
    await page.reload();
    await page.waitForFunction(u=>cloud.user?.username===u,credentials.username);
    await page.locator('#nav [data-tab="treino"]').click();
    assert.ok(await page.locator('input[data-field="kg"]').count());
    const snapshot={sessions:[{id:'synthetic-partial',code:'A',date:'2026-10-28',status:'partial',exercises:[{name:'Supino máquina',sets:[{kg:20,reps:10}]}]}],weights:[{date:'2026-10-28',weight:64}],drafts:{},checks:{},journal:[],extraExercises:{},exerciseChoices:{},profile:{initialWeight:62,targetWeight:70}};
    let response=await ctx.request.put(lab.origin+'/api/state',{headers:{origin:lab.origin},data:{baseRevision:0,data:snapshot}});
    assert.equal(response.status(),200);assert.equal((await response.json()).revision,1);
    snapshot.weights.push({date:'2026-10-29',weight:64.5});
    response=await ctx.request.put(lab.origin+'/api/state',{headers:{origin:lab.origin},data:{baseRevision:1,data:snapshot}});
    assert.equal(response.status(),200);assert.equal((await response.json()).revision,2);
    assert.deepEqual((await (await ctx.request.get(lab.origin+'/api/state')).json()).data,snapshot);
    assert.equal((await ctx.request.put(lab.origin+'/api/state',{headers:{origin:'https://outside.invalid'},data:{baseRevision:2,data:snapshot}})).status(),403);
    const other=await browser.newContext({ignoreHTTPSErrors:true});
    const salt=(await (await other.request.get(lab.origin+'/api/auth/salt?username=qa_outro')).json()).salt;
    const proof=require('node:crypto').pbkdf2Sync(credentials.password,Buffer.from(salt,'hex'),210000,32,'sha256').toString('hex');
    assert.equal((await other.request.post(lab.origin+'/api/auth/login',{headers:{origin:lab.origin},data:{username:'qa_outro',proof}})).status(),200);
    assert.equal((await (await other.request.get(lab.origin+'/api/state')).json()).data,null,'separate synthetic account has no snapshot');
    await other.close();
    const cookies=(await ctx.cookies()).map(c=>c.name+'='+c.value).join('; ');
    console.log('REAL_WORKER_SQLITE_LOGIN_WORKOUT_RELOAD_PASS');
    console.log('SQLITE_REVISION_BATCH_AND_ACCOUNT_ISOLATION_PASS');
    await browser.close();browser=null;await lab.close();lab=null;
    lab=await createLab({port:0,directory});
    const request=(url,cookie='')=>new Promise((resolve,reject)=>require('node:https').get(url,{rejectUnauthorized:false,headers:{cookie}},res=>{let body='';res.on('data',c=>body+=c);res.on('end',()=>resolve({status:res.statusCode,data:JSON.parse(body)}));}).on('error',reject));
    assert.equal((await request(lab.origin+'/api/health')).status,200);
    assert.equal((await request(lab.origin+'/api/auth/me')).status,401);
    const restored=await request(lab.origin+'/api/state',cookies);
    assert.equal(restored.status,200);assert.deepEqual(restored.data.data,snapshot);assert.equal(restored.data.revision,2);
    console.log('SQLITE_RESTART_AND_ANONYMOUS_REJECTION_PASS');
  }finally{if(browser)await browser.close();if(lab)await lab.close();fs.rmSync(directory,{recursive:true,force:true});}
})().catch(e=>{console.error(e);process.exitCode=1;});
