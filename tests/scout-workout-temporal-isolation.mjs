import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const ctx={window:{}};
vm.runInNewContext(fs.readFileSync(new URL('../public/scout-progress.js',import.meta.url),'utf8'),ctx);
const render=ctx.window.forjaScoutWorkoutProgress;
const now=new Date('2026-10-10T12:00:00Z');
const base={id:'passado',date:'2026-10-02',code:'A',status:'complete',exercises:[{id:'e1',name:'Supino',equipment:'maquina-A',sets:[{kg:30,reps:10}]}]};
const prior={id:'anterior',date:'2026-10-01',code:'A',status:'complete',exercises:[{id:'e1',name:'Supino',equipment:'maquina-A',sets:[{kg:28,reps:10}]}]};
const clean=render({sessions:[prior,base]},'passado',now);
assert.match(clean,/Resumo do treino/);
const future={...structuredClone(base),date:'2026-10-20',exercises:[{id:'e1',name:'Supino',equipment:'maquina-A',sets:[{kg:99,reps:10}]}]};
const malformed={...structuredClone(base),date:'2026-02-30'};
assert.equal(render({sessions:[prior,base,future]},'passado',now),clean,'cópia futura não pode tornar passado ambíguo');
assert.equal(render({sessions:[prior,base,malformed]},'passado',now),clean,'data inválida não pode tornar passado ambíguo');
const conflict={...structuredClone(base),exercises:[{id:'e1',name:'Supino',equipment:'maquina-A',sets:[{kg:77,reps:10}]}]};
assert.match(render({sessions:[prior,base,conflict]},'passado',now),/sem identificação única/,'conflito legítimo deve ser rejeitado');
const same=structuredClone(base);
assert.match(render({sessions:[prior,base,same]},'passado',now),/sem identificação única/,'consulta individual permanece conservadora com duplicata de mesmo ID');
console.log('WORKOUT_TEMPORAL_PASS');
