const assert=require('node:assert/strict'),fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {webkit,devices}=require('playwright');
(async()=>{
 const {createLab,credentials}=await import('../ops/lab-local.mjs');
 const directory=fs.mkdtempSync(path.join(os.tmpdir(),'forja-series-'));let lab,browser;
 try{
  lab=await createLab({port:0,directory});browser=await webkit.launch();
  const ctx=await browser.newContext({...devices['iPhone 13'],ignoreHTTPSErrors:true});const page=await ctx.newPage();
  await ctx.route('**/*',r=>new URL(r.request().url()).hostname==='localhost'?r.continue():r.abort());
  await page.goto(lab.origin);await page.locator('[data-action="welcomeLogin"]').click();await page.locator('#welcomeCover').waitFor({state:'hidden'});
  await page.locator('#cloudUser').fill(credentials.username);await page.locator('#cloudPassword').fill(credentials.password);await page.locator('[data-action="cloudLogin"]').click();
  await page.waitForFunction(u=>cloud.user?.username===u,credentials.username);await page.locator('#nav [data-tab="treino"]').click();
  await page.locator('.forja-ex-summary').first().click();
  const row=page.locator('.exercise .set').first(),kg=row.locator('[data-field="kg"]'),reps=row.locator('[data-field="reps"]'),done=row.locator('[data-field="done"]');
  await kg.fill('20');await reps.fill('10');
  const beforeBlur=await done.isChecked();
  await page.locator('.exercise .set').nth(1).locator('[data-field="kg"]').click();
  const auto=await done.isChecked();const autoRest=await page.evaluate(()=>rest.phase);
  await done.uncheck();await page.evaluate(()=>restReset());await done.check();
  const manualRest=await page.evaluate(()=>rest.phase);
  await page.evaluate(()=>{document.querySelectorAll('.exercise .set')[1].scrollIntoView({block:'start'});restRefresh();});
  const visibleTimer=await page.evaluate(()=>['restDisplay','restDockTime'].some(id=>{const e=document.getElementById(id),r=e.getBoundingClientRect();return r.width>0&&r.height>0&&r.top>=0&&r.bottom<=innerHeight;}));
  console.log('OBSERVED',JSON.stringify({beforeBlur,auto,autoRest,manualRest,visibleTimer}));
  assert.equal(beforeBlur,false,'typing does not complete before committing the field');
  assert.equal(auto,true,'valid values complete the set on field commit');
  assert.equal(autoRest,'running','auto completion starts rest');
  assert.equal(manualRest,'running','manual completion starts rest');
  assert.equal(visibleTimer,true,'one countdown remains visible next to the workout');
  const timerCount=()=>page.evaluate(()=>['restDisplay','restDockTime'].filter(id=>{const r=document.getElementById(id).getBoundingClientRect();return r.width>0&&r.height>0&&r.top>=0&&r.bottom<=innerHeight;}).length);
  assert.equal(await timerCount(),1,'only one timer is visible');
  const deadline=await page.evaluate(()=>rest.endAt);
  await reps.fill('11');await page.locator('.exercise .set').nth(1).locator('[data-field="kg"]').click();
  assert.equal(await page.evaluate(()=>rest.endAt),deadline,'editing an already completed set does not restart rest');
  await kg.fill('');await reps.click();assert.equal(await done.isChecked(),false,'empty actual load unchecks set');
  await reps.fill('0');await kg.fill('20');await reps.click();assert.equal(await done.isChecked(),false,'zero reps do not complete');
  await kg.fill('-1');await reps.fill('10');await page.locator('.exercise .set').nth(1).locator('[data-field="kg"]').click();assert.equal(await done.isChecked(),false,'negative load does not complete');
  await kg.fill('0');await reps.click();assert.equal(await done.isChecked(),true,'explicit zero kg is accepted');
  await done.uncheck();await page.evaluate(()=>restReset());
  const stored=await page.evaluate(()=>localStorage.getItem(KEY));
  page.on('dialog',dialog=>dialog.dismiss());
  await page.evaluate(()=>{window.labOriginalSetItem=Storage.prototype.setItem;Storage.prototype.setItem=function(k,v){if(k===KEY)throw new DOMException('synthetic quota','QuotaExceededError');return window.labOriginalSetItem.call(this,k,v);};});
  await done.click();
  assert.equal(await done.isChecked(),false,'failed save does not show completion');
  assert.equal(await page.evaluate(()=>rest.phase),'idle','failed save does not start timer');
  assert.equal(await page.evaluate(()=>localStorage.getItem(KEY)),stored,'failed save preserves stored snapshot');
  await page.evaluate(()=>{Storage.prototype.setItem=window.labOriginalSetItem;delete window.labOriginalSetItem;});
  await done.check();assert.equal(await done.isChecked(),true,'retry saves completion');
  await page.reload();await page.waitForFunction(u=>cloud.user?.username===u,credentials.username);
  await page.locator('#nav [data-tab="treino"]').click();await page.locator('.forja-ex-summary').first().click();
  assert.equal(await page.locator('.exercise .set').first().locator('[data-field="done"]').isChecked(),true,'completion survives reload');
  console.log('SERIES_BOUNDARIES_NO_DUPLICATE_TIMER_SAVE_FAILURE_RELOAD_PASS');
  console.log('SERIES_AUTO_MANUAL_VISIBLE_REST_WEBKIT_PASS');
 }finally{if(browser)await browser.close();if(lab)await lab.close();fs.rmSync(directory,{recursive:true,force:true});}
})().catch(e=>{console.error(e);process.exitCode=1;});
